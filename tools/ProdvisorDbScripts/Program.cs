// Generates SQL scripts that recreate the PRODVISOR (DANSOFT) master-data tables used by the AI service
// (MASZYNY, MASZYNY_TYP, MASZYNY_RODZAJ_PARAMETRU, MASZYNY_PARAMETRY, MaterialsKind) with the snapshot data:
//   tools/prodvisor-db/dansoft-sqlserver.sql   - for a test SQL Server (same dialect as production)
//   tools/prodvisor-db/dansoft-postgres.sql    - for a local PostgreSQL (integration tests without SQL Server)
// Only the columns the service reads are created. Run: dotnet run, project tools/ProdvisorDbScripts
using System.Globalization;
using System.Text;
using System.Text.Json;

var root = FindRepoRoot();
var machines = JsonDocument.Parse(File.ReadAllText(Path.Combine(root, "samples", "prodvisor-snapshot.json"))).RootElement;
var materials = JsonDocument.Parse(File.ReadAllText(Path.Combine(root, "samples", "prodvisor-snapshot-materials.json"))).RootElement;
var outDir = Directory.CreateDirectory(Path.Combine(root, "tools", "prodvisor-db")).FullName;

foreach (var pg in new[] { false, true })
{
    string T(string t) => pg ? $"\"dbo\".\"{t}\"" : $"[dbo].[{t}]";
    string C(string c) => pg ? $"\"{c}\"" : $"[{c}]";
    string S(JsonElement e) => e.ValueKind == JsonValueKind.Null ? "NULL" : (pg ? "" : "N") + "'" + e.GetString()!.Replace("'", "''") + "'";
    string N(JsonElement e) => e.ValueKind == JsonValueKind.Null ? "NULL" : e.GetRawText();
    string B(JsonElement e) => e.ValueKind == JsonValueKind.Null ? "NULL" : pg ? (e.GetInt32() == 1 ? "true" : "false") : e.GetRawText();
    var text = pg ? "varchar" : "nvarchar";
    var bit = pg ? "boolean" : "bit";

    var sb = new StringBuilder();
    sb.AppendLine($"-- PRODVISOR (DANSOFT) master data for the AI technology generator - {(pg ? "PostgreSQL" : "SQL Server")}");
    sb.AppendLine("-- Generated by tools/ProdvisorDbScripts from samples/prodvisor-snapshot*.json");
    sb.AppendLine(pg ? "CREATE SCHEMA IF NOT EXISTS \"dbo\";" : "IF SCHEMA_ID('dbo') IS NULL EXEC('CREATE SCHEMA dbo');");
    foreach (var t in new[] { "MASZYNY_PARAMETRY", "MASZYNY", "MASZYNY_RODZAJ_PARAMETRU", "MASZYNY_TYP", "MaterialsKind", "STANOWISKO" })
        sb.AppendLine(pg ? $"DROP TABLE IF EXISTS {T(t)};" : $"IF OBJECT_ID('dbo.{t}') IS NOT NULL DROP TABLE {T(t)};");
    sb.AppendLine();

    sb.AppendLine($"CREATE TABLE {T("MASZYNY_TYP")} ({C("ID")} int PRIMARY KEY, {C("TYP_MASZYNY")} {text}(100));");
    sb.AppendLine($"CREATE TABLE {T("MASZYNY")} ({C("ID")} int PRIMARY KEY, {C("NR_MASZYNY")} {text}(50), {C("ID_TYP_MASZYNY")} int, " +
                  $"{C("NAZWA_MASZYNY")} {text}(200), {C("ID_RODZAJ_MASZYNY")} int, {C("VirtualMachine")} {bit});");
    // RODZAJ_PARAMETRU is a fixed-width char column in PRODVISOR (values are space padded) - kept that way on purpose.
    sb.AppendLine($"CREATE TABLE {T("MASZYNY_RODZAJ_PARAMETRU")} ({C("ID")} int PRIMARY KEY, {C("RODZAJ_PARAMETRU")} {(pg ? "char" : "nchar")}(100), " +
                  $"{C("TYP_PARAMETRU")} int, {C("JEDNOSTKA")} int);");
    sb.AppendLine($"CREATE TABLE {T("MASZYNY_PARAMETRY")} ({C("ID")} int {(pg ? "GENERATED BY DEFAULT AS IDENTITY" : "IDENTITY(1,1)")} PRIMARY KEY, " +
                  $"{C("ID_MASZYNY")} int, {C("ID_RODZAJ_PARAMETRU")} int, {C("WARTOSC")} decimal(18,4), {C("TEXT")} {text}(200));");
    sb.AppendLine($"CREATE TABLE {T("MaterialsKind")} ({C("ID")} int PRIMARY KEY, {C("Name")} {text}(300), {C("AlloyID")} int, {C("NoActive")} {bit});");
    // STANOWISKO: only the columns the service reads. NR_STANOWISKA is char(10) (space padded) like in PRODVISOR.
    sb.AppendLine($"CREATE TABLE {T("STANOWISKO")} ({C("ID")} int PRIMARY KEY, {C("NR_STANOWISKA")} {(pg ? "char" : "nchar")}(10), {C("ID_MASZYNY")} int, " +
                  $"{C("KOSZT_ROBOCZOGODZINY")} decimal(18,2), {C("NR_HALI")} int, {C("MultiOperation")} {bit}, {C("VirtualWorkplace")} {bit}, " +
                  $"{C("AuxiliaryNo")} {text}(10), {C("Multiperson")} {bit}, {C("WorkplacesGroup")} int);");
    sb.AppendLine();

    void Insert(string table, string[] cols, IEnumerable<string> rows)
    {
        foreach (var chunk in rows.Chunk(200))
        {
            sb.AppendLine($"INSERT INTO {T(table)} ({string.Join(", ", cols.Select(C))}) VALUES");
            sb.AppendLine(string.Join(",\n", chunk.Select(r => $"  ({r})")) + ";");
        }
    }

    Insert("MASZYNY_TYP", ["ID", "TYP_MASZYNY"], machines.GetProperty("maszyny_typ").EnumerateArray().Select(r => $"{N(r[0])}, {S(r[1])}"));
    Insert("MASZYNY", ["ID", "NR_MASZYNY", "ID_TYP_MASZYNY", "NAZWA_MASZYNY", "ID_RODZAJ_MASZYNY", "VirtualMachine"],
        machines.GetProperty("maszyny").EnumerateArray().Select(r => $"{N(r[0])}, {S(r[1])}, {N(r[2])}, {S(r[3])}, {N(r[4])}, {B(r[5])}"));
    Insert("MASZYNY_RODZAJ_PARAMETRU", ["ID", "RODZAJ_PARAMETRU", "TYP_PARAMETRU", "JEDNOSTKA"],
        machines.GetProperty("maszyny_rodzaj_parametru").EnumerateArray().Select(r => $"{N(r[0])}, {S(r[1])}, {N(r[2])}, {N(r[3])}"));
    Insert("MASZYNY_PARAMETRY", ["ID_MASZYNY", "ID_RODZAJ_PARAMETRU", "WARTOSC", "TEXT"],
        machines.GetProperty("maszyny_parametry").EnumerateArray().Select(r => $"{N(r[0])}, {N(r[1])}, {N(r[2])}, {S(r[3])}"));
    Insert("MaterialsKind", ["ID", "Name", "AlloyID", "NoActive"],
        materials.GetProperty("materials_kind").EnumerateArray().Select(r => $"{N(r[0])}, {S(r[1])}, {N(r[2])}, {B(r[3])}"));
    Insert("STANOWISKO", ["ID", "NR_STANOWISKA", "ID_MASZYNY", "KOSZT_ROBOCZOGODZINY", "NR_HALI", "MultiOperation", "VirtualWorkplace", "AuxiliaryNo", "Multiperson", "WorkplacesGroup"],
        machines.GetProperty("stanowisko").EnumerateArray().Select(r => $"{N(r[0])}, {S(r[1])}, {N(r[2])}, {N(r[3])}, {N(r[4])}, {B(r[5])}, {B(r[6])}, {S(r[7])}, {B(r[8])}, {N(r[9])}"));

    var file = Path.Combine(outDir, pg ? "dansoft-postgres.sql" : "dansoft-sqlserver.sql");
    File.WriteAllText(file, sb.ToString(), new UTF8Encoding(false));
    Console.WriteLine($"Saved {file}");
}

static string FindRepoRoot()
{
    var dir = new DirectoryInfo(AppContext.BaseDirectory);
    while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "ProdvisorAi.Demo.sln"))) dir = dir.Parent;
    return dir?.FullName ?? Directory.GetCurrentDirectory();
}
